export function translate(lang: Language, key: string, vars?: Record<string, string | number>): string {
  let text = translations[lang][key] ?? translations.ru[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  return text
}

export function useT() {
  const lang = useUserStore((s) => s.language)
  return (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars)
}

export async function setLanguage(userId: string, language: Language): Promise<void> {
  useUserStore.getState().setUser({ language })
  await api.post(`/api/user/${userId}/language`, { language }).catch(() => {})
}
